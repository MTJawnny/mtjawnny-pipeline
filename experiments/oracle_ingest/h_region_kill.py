#!/usr/bin/env python3
"""C03 — the seven interface/1 I3 H-REGION kill-condition tests (K1-K7).

Reads `experiments/out/oracle_ingest/c03/regions.json` (regenerated by
`h_region.py` if missing; HALTS if `h_region.py --verify` says it is stale) and
runs every test on every population clause and every fixture clause. Each test
yields KILL, UNRESOLVED or PASS per clause, exactly as interface/1 I3 defines
them: KILL only for what V1 §5 names; a failure of extraction or resolution is
UNRESOLVED and never a kill; otherwise PASS. It answers ATTACH-1, ATTACH-3 and
C2 only and adds no question.

DISTINCT REQUIRED OPERATIONS (I3) come from independent evidence only -- never
from candidate heads alone, and no single detector is a prerequisite:
  E1  a fixture whose accepted role asserts them (FIXTURES.json):
      `two-sequential-operations` (the two operations of its census clause) and
      `delayed-return-same-object` (the census exile and the legacy `return` of
      the later sentence -- the role's own recorded selection rule);
  E2  C2 asks about the exile and the return of a clause separately, when both
      print with their own instruction boundary under EITHER detector path;
  E3  ATTACH-1 asks about two census actions of one clause separately (two
      census rows owned by one occurrence).
Where none applies, K1 and K2 are UNRESOLVED -- never PASS, never KILL.

RELEVANCE, per condition, comes from the precommitted consumer questions and
FIXTURES.json roles, never from a detector alone; fixtures are always relevant.
A question APPLIES to a clause when: ATTACH-1 -- the clause carries a census
row (the census classified action X on an object class); C2 -- the clause
prints the frozen P3 `exile-and-return` form, or it belongs to the
delayed-return fixture; ATTACH-3 -- the clause prints a cost, condition,
duration or destination span.

RESULT PRECEDENCE: a KILL on a fixture or on a relevant population clause ->
'killed' for that condition; otherwise 'not killed on the P2 population'
(never 'confirmed'). UNRESOLVED is a finding for M04, not a verdict. A
condition with zero PASS over its relevant clauses and fixtures is flagged
'PASS coverage insufficient' -- an escalation, not a verdict.

    python3 experiments/oracle_ingest/h_region_kill.py                      # write
    python3 experiments/oracle_ingest/h_region_kill.py --emit               # stdout
    python3 experiments/oracle_ingest/h_region_kill.py --check-determinism  # x2
    python3 experiments/oracle_ingest/h_region_kill.py --verify
    python3 experiments/oracle_ingest/h_region_kill.py --check-not-killed
    python3 experiments/oracle_ingest/h_region_kill.py --check-decided
"""
