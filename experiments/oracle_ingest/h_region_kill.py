def questions(c: dict) -> list:
    q = []
    if c.get("census_key"):
        q.append("ATTACH-1")
    if _EXILE_RETURN.search(c["clause_text"]) or ROLE_DELAYED in c["fixture_roles"]:
        q.append("C2")
    if c["role_spans"]:
        q.append("ATTACH-3")
    return q


def required_operations(c: dict, by_id: dict, peers: dict) -> tuple:
    """(ops, evidence): the distinct required operations of clause `c` as
    [(clause id, head, head start)], or [] when no independent evidence
    establishes them."""
    ops, ev = [], []
    if ROLE_TWO_OPS in c["fixture_roles"] and c.get("census_key"):
        ops = [(_cid(c), h["head"], h["start"]) for h in c["heads_legacy"]]
        ev.append(f"FIXTURES.json role {ROLE_TWO_OPS}")
    if not ops and ROLE_DELAYED in c["fixture_roles"]:
        pair = delayed_pair(c, by_id)
        if pair:
            ops = pair
            ev.append(f"FIXTURES.json role {ROLE_DELAYED}")
    if not ops and "C2" in questions(c) and ROLE_DELAYED not in c["fixture_roles"]:
        both = {}
        for h in c["heads_legacy"] + c["heads_corrected"]:
            if h["head"] in ("exile", "return") and h["head"] not in both:
                both[h["head"]] = h["start"]
        if len(both) == 2:
            ops = [(_cid(c), "exile", both["exile"]), (_cid(c), "return", both["return"])]
            ev.append("C2 asks about the exile and the return separately; each "
                      "prints its own instruction boundary under a detector path")
    if not ops and len(peers.get(_cid(c), [])) > 1:
        for stem, _occ in sorted(peers[_cid(c)]):
            h = next((h for h in c["heads_legacy"] if h["head"] == _word(stem)), None)
            ops.append((_cid(c), _word(stem), h["start"] if h else -1))
        ev.append("ATTACH-1 asks about two census actions of this occurrence")
    return ops, ev


def delayed_pair(c: dict, by_id: dict):
    """The delayed-return role's own pair: its census exile clause and the
    later sentence of the same paragraph carrying a legacy `return` head."""
    oid, fi, pi = (c["address"][k] for k in ("oracle_id", "face", "paragraph"))
    sibs = sorted((x for x in by_id.values()
                   if ROLE_DELAYED in x["fixture_roles"]
                   and (x["address"]["oracle_id"], x["address"]["face"],
                        x["address"]["paragraph"]) == (oid, fi, pi)),
                  key=lambda x: x["address"]["clause"])
    home = next((x for x in sibs if x.get("census_key")
                 and x["census_key"][0] == "exile"), None)
    if home is None:
        return None
    later = next((x for x in sibs if x["address"]["clause"] > home["address"]["clause"]
                  and any(h["head"] == "return" for h in x["heads_legacy"])), None)
    if later is None:
        return None
    ex = next(h for h in home["heads_legacy"] if h["head"] == "exile")
    rt = next(h for h in later["heads_legacy"] if h["head"] == "return")
    if _cid(c) not in (_cid(home), _cid(later)):
        return None
    return [(_cid(home), "exile", ex["start"]), (_cid(later), "return", rt["start"])]


def region_of(op: tuple, by_id: dict):
    """(region, reason). None with a reason when the region was not derived."""
    cid, head, start = op
    c = by_id[cid]
    if not any(h["head"] == head and h["start"] == start for h in c["heads_legacy"]):
        return None, (f"{head}@{start} is not a legacy head of {cid}: its region "
                      f"was not derived (extraction failure)")
    hit = [r for r in c["regions"] if r["head_span"][0] == start and r["head"] == head]
    if len(hit) != 1:
        return None, f"legacy head {head}@{start} owns {len(hit)} regions"
    return hit[0], ""


# ---------------------------------------------------------------- the tests

def k1(c, ops, by_id):
    if len(ops) < 2:
        return {"outcome": UNRESOLVED,
                "reason": "the heads are not shown to be distinct required operations "
                          "by independent evidence"}
    got = []
    for op in ops:
        r, why = region_of(op, by_id)
        if r is None and "extraction failure" in why:
            return {"outcome": UNRESOLVED, "reason": why}
        if r is None:
            return {"outcome": KILL, "reason": why}
        got.append((op, r))
    keys = [(op[0], r["ordinal"]) for op, r in got]
    if len(set(keys)) != len(keys):
        return {"outcome": KILL, "reason": "two distinct required operations share one "
                                           "region"}
    for op, r in got:
        a, b = r["span"]
        if not (0 <= a < b <= len(by_id[op[0]]["clause_text"])) or r["owner"] != op[0]:
            return {"outcome": KILL, "reason": f"region of {op[1]} is not source-spanned "
                                               f"inside, and owned by, its occurrence"}
    return {"outcome": PASS, "reason": "each distinct required operation has its own "
                                       "source-spanned region owned by its occurrence"}


def k2(c, ops, by_id):
    if len(ops) < 2:
        return {"outcome": UNRESOLVED,
                "reason": "the heads are not shown to be distinct required operations "
                          "by independent evidence"}
    same = [(x, y) for i, x in enumerate(ops) for y in ops[i + 1:] if x[1] == y[1]]
    for x, y in same:
        rx, wx = region_of(x, by_id)
        ry, wy = region_of(y, by_id)
        if rx is None or ry is None:
            why = wx or wy
            return {"outcome": UNRESOLVED if "extraction failure" in why else KILL,
                    "reason": why}
        if (x[0], rx["span"]) == (y[0], ry["span"]):
            return {"outcome": KILL, "reason": f"two required {x[1]} operations have "
                                               f"the same span"}
    return {"outcome": PASS, "reason": "no two required operations share a head" if not
            same else "repeated required operations are told apart by span"}


def relations(c: dict) -> list:
    """The relations the clause states between its operations or their objects,
    among P4's frozen candidate structures, plus printed `then` sequencing.
    Positions inside a quoted created ability are excluded, as P4 excludes them."""
    text, (lo, hi) = c["clause_text"], c["scope"]
    quoted = hr.fx.quoted_spans(text)
    inq = lambda p: any(a <= p < b for a, b in quoted)
    out, covered = [], []
    for ph, rx in sorted(aq._CR607_RES.items()):
        for m in rx.finditer(text):
            if lo <= m.start() < hi and not inq(m.start()):
                out.append({"kind": "cr607-linkage", "pos": m.start(),
                            "phrase": m.group(0).strip().lower()})
                covered.append((m.start(), m.end()))
    for rx in (aq._PRONOUN_RE, aq._BACKREF_RE):
        for m in rx.finditer(text):
            if (lo <= m.start() < hi and not inq(m.start())
                    and not any(a <= m.start() < b for a, b in covered)):
                out.append({"kind": "back-reference", "pos": m.start(),
                            "phrase": m.group(1).lower()})
    for s in c["role_spans"]:
        if "condition-marker" in s["rules"] and lo <= s["span"][0] < hi:
            out.append({"kind": "conditional", "pos": s["span"][0], "span": s})
    for m in aq._DELAYED.finditer(text):
        if lo <= m.start() < hi and not inq(m.start()):
            out.append({"kind": "delayed", "pos": m.start()})
    heads = c["heads_region"]                  # R2: dropped heads start no region
    for i in range(1, len(heads)):
        con = heads[i]["connector"]
        if con is not None and text[con:con + 4].lower() == "then":
            out.append({"kind": "sequencing", "pos": con, "between": [i - 1, i]})
    return sorted(out, key=lambda r: (r["pos"], r["kind"]))


def _candidates(c: dict, region: dict) -> int:
    """Candidate referent spans in a region: each frozen P3 participant
    (CR 601.2c). Only where the region prints no participant does a
    non-possessive object back-reference stand in as its referent span
    (`exile it, then return it`): a pronoun beside a printed participant is a
    reference, not a second referent."""
    a, b = region["span"]
    seg = c["clause_text"][a:b]
    n = len(aq.participants(seg))
    if n:
        return n
    return sum(1 for m in aq._PRONOUN_RE.finditer(seg)
               if m.group(1).lower() not in _POSSESSIVES)


_R3_COORD = re.compile(r",\s*and\b(?!/)|,|\band\b(?!/)", re.I)


def _has_boundary_word(gap: str) -> bool:
    """A frozen `_BOUNDARY_WORD` printed anywhere in `gap` (tested at every
    word end, as the frozen rule tests the text before a head)."""
    for i in range(1, len(gap) + 1):
        if i < len(gap) and (gap[i].isalnum() or gap[i] in "'’"):
            continue
        m = aq._BOUNDARY_WORD.search(gap[:i])
        if m and gap[m.start():i].strip():
            return True
    return False


def r3_list(seg: str, n: int):
    """interface/2 §I3a R3: the printed coordinated list of a region segment
    holding `n` candidates, as [[start, end, kind]] P3 marks in printed order,
    or None when membership cannot be established (fail closed)."""
    marks = [[m.start(), m.end(), "target"] for m in aq._TARGET_TOKEN.finditer(seg)]
    second = ol._SECOND_OBJECT.search(seg)
    if second:
        marks.append([second.start(), second.end(), "second-object"])
    marks.sort()
    if len(marks) < 2 or len(marks) != n:
        return None                       # every candidate must be a member
    for prev, nxt in zip(marks, marks[1:]):
        end = nxt[0] if nxt[2] == "target" else nxt[1]
        if end < prev[1]:
            return None
        gap = seg[prev[1]:end]
        coords = list(_R3_COORD.finditer(gap))
        if len(coords) != 1:
            return None
        rest = gap[:coords[0].start()] + " " + gap[coords[0].end():]
        if (aq._HEAD_RE.search(gap) or re.search(r"[.;:]", gap)
                or _has_boundary_word(rest)):
            return None
    return marks


def k3_relation(c: dict, rel: dict, r3: bool = True) -> dict:
    regions = c["regions"]
    if not regions:
        return {"outcome": UNRESOLVED, "reason": "no region was derived (extraction failure)"}
    kind = rel["kind"]
    if kind == "sequencing":
        i, j = rel["between"]
        ends = [r["ordinal"] for k in (i, j) for r in regions
                if r["head_span"][0] == c["heads_region"][k]["start"]]
        ok = len(ends) == 2
        return {"outcome": PASS if ok else KILL, "endpoint_regions": ends,
                "reason": "both sequenced operations are named by their own region"
                if ok else "a sequenced operation maps to no region"}
    if kind == "conditional":
        s = rel["span"]
        ends = list(s["attached"])
        if s["outcome"] == "attached":
            return {"outcome": PASS, "endpoint_regions": ends,
                    "reason": "the conditioned operation is one region"}
        if s["outcome"] == "no_region":
            return {"outcome": UNRESOLVED, "reason": s["reason"]}
        return {"outcome": KILL, "endpoint_regions": ends,
                "reason": f"the conditional endpoint maps to {len(ends)} regions: "
                          f"{s['reason']}"}
    home = _in_region(regions, rel["pos"])
    if kind == "delayed":
        if len(home) == 1:
            return {"outcome": PASS, "endpoint_regions": [home[0]["ordinal"]],
                    "reason": "the delayed operation is one region"}
        if not home and rel["pos"] < regions[0]["span"][0]:
            ends = [r["ordinal"] for r in regions]
            return {"outcome": PASS if len(ends) == 1 else KILL, "endpoint_regions": ends,
                    "reason": f"an ability-prefix delay governs {len(ends)} region(s)"}
        return {"outcome": KILL, "endpoint_regions": [],
                "reason": "the delayed endpoint lies between regions and maps to none"}
    # back-reference / CR 607 linkage: the referring endpoint, then the antecedent.
    if not home:
        # Text outside every region is text no region was derived for (an
        # ability prefix, or an operation whose head was not extracted).
        return {"outcome": UNRESOLVED,
                "reason": f"the referring phrase {rel['phrase']!r} lies outside every "
                          f"derived region (no region was derived for its text)"}
    if len(home) != 1:
        return {"outcome": KILL, "reason": f"the referring phrase {rel['phrase']!r} maps "
                                           f"to {len(home)} regions",
                "endpoint_regions": [r["ordinal"] for r in home]}
    k = home[0]["ordinal"]
    earlier = [r for r in regions if r["ordinal"] < k]
    if not earlier:
        return {"outcome": UNRESOLVED, "endpoint_regions": [k],
                "reason": f"{rel['phrase']!r} is named in the clause's first region; its "
                          f"referent is not an earlier operation of this clause "
                          f"(reference resolution is C04's work)"}
    if rel.get("phrase") in _EVENT_REFS:
        ends = [k] + [r["ordinal"] for r in earlier]
        if len(earlier) == 1:
            return {"outcome": PASS, "endpoint_regions": ends,
                    "reason": "the referenced operation is one region"}
        return {"outcome": KILL, "endpoint_regions": ends,
                "reason": f"{rel['phrase']!r} maps to {len(earlier)} earlier operation "
                          f"regions"}
    with_cand = [(r, _candidates(c, r)) for r in earlier]
    with_cand = [(r, n) for r, n in with_cand if n]
    ends = [k] + [r["ordinal"] for r, _ in with_cand]
    if not with_cand:
        return {"outcome": UNRESOLVED, "endpoint_regions": [k],
                "reason": f"no candidate referent span was extracted for "
                          f"{rel['phrase']!r}"}
    if len(with_cand) > 1:
        return {"outcome": KILL, "endpoint_regions": ends,
                "reason": f"{rel['phrase']!r} maps to {len(with_cand)} regions"}
    if with_cand[0][1] > 1:
        region, n = with_cand[0]
        marks = (r3_list(c["clause_text"][region["span"][0]:region["span"][1]], n)
                 if r3 and rel.get("phrase") in hr.R3_PLURAL_MARKERS else None)
        if marks:
            # interface/2 §I3a R3: named (the list); its meaning is C04's.
            return {"outcome": UNRESOLVED, "endpoint_regions": ends, "r3": True,
                    "list_marks": [[region["span"][0] + a, region["span"][0] + b, k]
                                   for a, b, k in marks],
                    "reason": f"R3: {rel['phrase']!r} names one printed coordinated "
                              f"list of {n} candidates in region {region['ordinal']}; "
                              f"whether it means the whole list or part of it is "
                              f"reference resolution (C04)"}
        return {"outcome": KILL, "endpoint_regions": ends,
                "reason": f"{rel['phrase']!r} has {with_cand[0][1]} candidate referent "
                          f"spans inside region {with_cand[0][0]['ordinal']}"}
    return {"outcome": PASS, "endpoint_regions": ends,
            "reason": f"{rel['phrase']!r} names one candidate span in region "
                      f"{with_cand[0][0]['ordinal']}"}


def k3(c, r3: bool = True):
    rels = relations(c)
    items = [dict(k3_relation(c, r, r3), kind=r["kind"], pos=r["pos"]) for r in rels]
    if not items:
        return {"outcome": PASS, "reason": "the clause states no relation", "relations": []}
    return {"outcome": _outcome(items), "relations": items,
            "reason": f"{len(items)} relation(s)"}


def k4(c):
    items = []
    for s in c["role_spans"]:
        if s["outcome"] == "attached" and s.get("attached_to") == "ability":
            # interface/2 §I3a R1: ONE attachment, to the ability.
            items.append({"outcome": PASS, "role": s["role"], "span": s["span"],
                          "r1_shape": s["r1_shape"],
                          "reason": f"R1 {s['r1_shape']}: attached once, to the ability "
                                    f"({len(s['attached'])} region(s))"})
        elif s["outcome"] == "attached":
            items.append({"outcome": PASS, "role": s["role"], "span": s["span"],
                          "reason": "attached to one region"})
        elif s["outcome"] == "no_region":
            items.append({"outcome": UNRESOLVED, "role": s["role"], "span": s["span"],
                          "reason": s["reason"]})
        else:
            items.append({"outcome": KILL, "role": s["role"], "span": s["span"],
                          "reason": f"attachable to {len(s['attached'])} regions by the "
                                    f"derivation rule: {s['reason']}"})
    if not items:
        return {"outcome": PASS, "reason": "the clause prints no ATTACH-3 span", "spans": []}
    return {"outcome": _outcome(items), "spans": items, "reason": f"{len(items)} span(s)"}


def k5(c):
    regions = c["regions"]
    only_corr = c["detector_diff"]["only_corrected"]
    for head, pos in only_corr:
        if _in_region(regions, pos):
            return {"outcome": UNRESOLVED,
                    "reason": f"the corrected head {head}@{pos} lies inside a derived "
                              f"region but got none of its own (extraction failure)"}
    pairs = c["overlaps"]
    for i, j in pairs:
        x, y = regions[i], regions[j]
        if x["span"] == y["span"] and x["head"] == y["head"]:
            return {"outcome": KILL, "reason": f"regions {i} and {j} overlap with the same "
                                               f"span and head: no rule tells them apart"}
    if pairs:
        return {"outcome": PASS, "reason": f"{len(pairs)} overlap(s); identities told "
                                           f"apart by head span", "pairs": pairs}
    return {"outcome": PASS, "reason": "no two regions overlap or nest"}


def k6(c, ops, by_id, fired):
    if fired:
        return {"outcome": PASS, "reason": f"{', '.join(fired)} fire(s) on this clause; K6 "
                                           f"requires that K1-K5 do not"}
    q = questions(c)
    needs, unresolved = [], []
    if "ATTACH-1" in q:
        w = _word(c["census_key"][0])
        hit = [r for r in c["regions"] if r["head"] == w]
        if not hit:
            unresolved.append(f"ATTACH-1: no region for action {w!r} (extraction failure)")
    if "C2" in q:
        pair = [op for op in ops if op[1] in ("exile", "return")]
        if len(pair) < 2:
            unresolved.append("C2: the exile and the return are not both extracted")
        else:
            got = [region_of(op, by_id) for op in pair]
            if any(r is None for r, _ in got):
                unresolved.append("C2: " + next(w for r, w in got if r is None))
            else:
                needs.append(("C2 exile vs return",
                              [(op[0], r["ordinal"]) for op, (r, _) in zip(pair, got)]))
    if "ATTACH-3" in q:
        if any(s["outcome"] == "no_region" for s in c["role_spans"]):
            unresolved.append("ATTACH-3: a span has no region (extraction failure)")
        if ROLE_SPLIT in c["fixture_roles"]:
            dest = [s for s in c["role_spans"] if s["role"] == "destination"
                    and s["outcome"] == "attached"]
            if len(dest) >= 2:
                needs.append(("ATTACH-3 split destinations (FIXTURES.json role "
                              f"{ROLE_SPLIT})", [(_cid(c), s["attached"][0]) for s in dest]))
    if len(ops) >= 2 and not unresolved:
        got = [region_of(op, by_id) for op in ops]
        if all(r is not None for r, _ in got):
            needs.append(("distinct required operations",
                          [(op[0], r["ordinal"]) for op, (r, _) in zip(ops, got)]))
    for label, keys in needs:
        if len(set(keys)) != len(keys):
            return {"outcome": KILL, "reason": f"{label}: the answer must tell apart items "
                                               f"that share one region of one occurrence"}
    if unresolved:
        return {"outcome": UNRESOLVED, "reason": "; ".join(unresolved)}
    return {"outcome": PASS, "reason": "every applicable question is answerable at region "
                                       "plus occurrence identity" if q else
            "no ATTACH-1, ATTACH-3 or C2 question applies"}


def k7_rules(rules: list, names: list) -> dict:
    """The rule table: halts in `hr.assert_not_card_keyed` become a KILL here."""
    try:
        with contextlib.redirect_stderr(io.StringIO()) as err:
            hr.assert_not_card_keyed(rules, names)
    except SystemExit:
        return {"outcome": KILL, "reason": err.getvalue().strip().replace("STOP — ", "")}
    return {"outcome": PASS, "reason": "every rule carries a CR anchor and none is keyed "
                                       "to a card, name or oracle_id"}


def k7(c, rules_verdict, rule_ids):
    if rules_verdict["outcome"] == KILL:
        return rules_verdict
    text, (lo, hi) = c["clause_text"], c["scope"]
    heads = c["heads_region"]                  # R2: dropped heads start no region
    for r in c["regions"]:
        if r["start_rule"] not in rule_ids or r["end_rule"] not in rule_ids:
            return {"outcome": KILL, "reason": f"region {r['ordinal']} uses a rule outside "
                                               f"the derivation table"}
        i = r["ordinal"]
        if i >= len(heads) or r["span"][0] != heads[i]["start"]:
            return {"outcome": KILL, "reason": f"region {i} does not start at its printed head"}
        if i + 1 < len(heads):
            nxt = heads[i + 1]
            end = max(nxt["connector"] if nxt["connector"] is not None else nxt["start"],
                      heads[i]["end"])
        else:
            end = hi
        while end > heads[i]["end"] and text[end - 1] in " ,;:.":
            end -= 1
        if r["span"][1] != end:
            return {"outcome": KILL, "reason": f"region {i} does not end at a printed "
                                               f"connector or its clause scope"}
    return {"outcome": PASS, "reason": "every boundary is a printed head, a printed "
                                       "connector or the clause scope"}


# ----------------------------------------------------------------- relevance

def relevance(c: dict, ops: list, outcomes: dict) -> dict:
    q = questions(c)
    fx_roles = [f"FIXTURES.json role {r}" for r in c["fixture_roles"]]
    out = {}
    why12 = ([f"distinct required operations ({len(ops)})"] if len(ops) >= 2 else [])
    out["K1"] = why12 + fx_roles
    out["K2"] = list(out["K1"])
    k3q = []
    if "C2" in q:
        k3q.append("C2")
    if "ATTACH-1" in q:
        # ATTACH-1 names the census action and its object: a relation whose
        # referring phrase or any endpoint lies in that action's region.
        w = _word(c["census_key"][0])
        own = [r for r in c["regions"] if r["head"] == w]
        mine = {r["ordinal"] for r in own}
        rels = outcomes["K3"].get("relations", [])
        if any(_in_region(own, r["pos"]) or mine & set(r.get("endpoint_regions", []))
               for r in rels):
            k3q.append("ATTACH-1")
    out["K3"] = k3q + fx_roles
    out["K4"] = (["ATTACH-3"] if "ATTACH-3" in q else []) + fx_roles
    k5 = outcomes["K5"]
    out["K5"] = ([x for x in q] if (c["overlaps"] or k5["outcome"] != PASS) and q
                 else []) + fx_roles
    out["K6"] = list(q) + fx_roles
    out["K7"] = ["every clause and fixture"] + fx_roles
    return {k: {"relevant": bool(v), "because": v} for k, v in out.items()}


# ---------------------------------------------------------------- evaluation

def rule_view(c: dict, r1: bool, r2: bool) -> dict:
    """Clause `c` with R1 and/or R2 switched off: the interface/1 regions (every
    legacy head starts one) and/or no R1 attachment. Used ONLY to report what
    each rule changed; outcomes are always those of the full interface/2 view."""
    text, (lo, hi) = c["clause_text"], c["scope"]
    regions = (c["regions"] if r2 else
               hr.derive_regions(text, lo, hi, c["address"], r2=False)[0])
    bases = [{k: s[k] for k in ("role", "span", "rules")} for s in c["role_spans"]]
    spans = []
    for b in bases:
        shape = hr.r1_shape(text, b, bases) if r1 else None
        spans.append(dict(b, **hr.attach(b, regions, shape)))
    pairs = [(x, y) for i, x in enumerate(regions) for y in regions[i + 1:]]
    return dict(c, regions=regions, role_spans=spans,
                heads_region=c["heads_region"] if r2 else c["heads_legacy"],
                overlaps=[[x["ordinal"], y["ordinal"]] for x, y in pairs
                          if x["span"][0] < y["span"][1] and y["span"][0] < x["span"][1]])


def interface1_changes(records: list, rules: list, names: list, full: dict) -> list:
    """Per clause and condition, the interface/1 outcome beside the interface/2
    one wherever they differ, and the rule(s) whose effect alone changes it."""
    for c in records:
        got = [{k: v for k, v in s.items() if k != "interface1"} for s in c["role_spans"]]
        if rule_view(c, True, True)["role_spans"] != got:
            fc.halt(f"re-attaching {_cid(c)} does not reproduce regions.json")
    view = lambda r1, r2, r3: evaluate([rule_view(c, r1, r2) for c in records],
                                       rules, names, r3)["clauses"]
    i1 = view(False, False, False)
    alone = {"R1": view(True, False, False), "R2": view(False, True, False),
             "R3": view(False, False, True)}
    out = []
    for n, row in enumerate(full["clauses"]):
        for k in CONDITIONS:
            now, was = row["tests"][k], i1[n]["tests"][k]
            if now["outcome"] != was["outcome"]:
                by = [r for r in ("R1", "R2", "R3")
                      if alone[r][n]["tests"][k]["outcome"] != was["outcome"]]
                row.setdefault("interface1_changes", {})[k] = {
                    "interface1": was["outcome"], "interface1_relevant": was["relevant"],
                    "interface2": now["outcome"], "changed_by": by}
                out.append([row["id"], row["census_key"], k, was["outcome"],
                            now["outcome"], by])
    return sorted(out, key=lambda x: (x[2], x[0], x[1] or []))


def rule_reach(records: list, rows: list) -> dict:
    fired = {
        "R1 attach-ability-prefix": lambda c, r: any(s.get("attached_to") == "ability"
                                                     for s in c["role_spans"]),
        "R2 head-not-payment-cast": lambda c, r: bool(c["r2_dropped_heads"]),
        "R3 group-back-reference": lambda c, r: any(
            x.get("r3") for x in r["tests"]["K3"].get("relations", [])),
    }
    out = {}
    for rule, hit in fired.items():
        pop = sorted({_cid(c) for c, r in zip(records, rows) if c["population"] and hit(c, r)})
        fix = sorted({_cid(c) for c, r in zip(records, rows)
                      if c["fixture_roles"] and hit(c, r)})
        out[rule] = {"population": {"count": len(pop), "clauses": pop},
                     "fixtures": {"count": len(fix), "clauses": fix}}
    return out


def evaluate(records: list, rules: list, names: list, r3: bool = True) -> dict:
    by_id = {}
    for c in records:
        by_id.setdefault(_cid(c), c)
    peers = {}
    for c in records:
        if c.get("census_key"):
            peers.setdefault(_cid(c), set()).add(tuple(c["census_key"]))
    rules_verdict = k7_rules(rules, names)
    rule_ids = {r.get("id") for r in rules}
    rows = []
    for c in records:
        ops, ev = required_operations(c, by_id, peers)
        o = {"K1": k1(c, ops, by_id), "K2": k2(c, ops, by_id), "K3": k3(c, r3),
             "K4": k4(c), "K5": k5(c)}
        fired = [k for k in ("K1", "K2", "K3", "K4", "K5") if o[k]["outcome"] == KILL]
        o["K6"] = k6(c, ops, by_id, fired)
        o["K7"] = k7(c, rules_verdict, rule_ids)
        rel = relevance(c, ops, o)
        rows.append({"id": _cid(c), "census_key": c.get("census_key"),
                     "population": c["population"], "fixture_roles": c["fixture_roles"],
                     "questions": questions(c),
                     "distinct_required_operations": [list(op) for op in ops],
                     "operations_evidence": ev,
                     "tests": {k: dict(o[k], **rel[k]) for k in CONDITIONS}})
    return {"clauses": rows, "conditions": summarize(rows), "rule_table": rules_verdict}


def _label(r: dict) -> list:
    return [r["id"], r["census_key"]]


def summarize(rows: list) -> dict:
    out = {}
    for k in CONDITIONS:
        allc = {o: [] for o in (PASS, UNRESOLVED, KILL)}
        relc = {o: [] for o in (PASS, UNRESOLVED, KILL)}
        for r in rows:
            t = r["tests"][k]
            allc[t["outcome"]].append(_label(r))
            if r["fixture_roles"] or t["relevant"]:
                relc[t["outcome"]].append(_label(r))
        killed = bool(relc[KILL])
        n_rel = sum(len(v) for v in relc.values())
        out[k] = {
            "all": {o: {"count": len(v), "clauses": v} for o, v in allc.items()},
            "relevant": {"count": n_rel,
                         **{o: {"count": len(v), "clauses": v} for o, v in relc.items()}},
            "result": RESULT_KILLED if killed else RESULT_NOT_KILLED,
            "pass_coverage": COVERAGE_FLAG if not relc[PASS] else "sufficient",
        }
    return out


def not_killed_failures(report: dict) -> list:
    """Every KILL on a fixture or on a population clause relevant to that
    condition. Negative-control records live elsewhere and are never read."""
    return [[k, cid] for k, d in sorted(report["conditions"].items())
            for cid, _ck in d["relevant"][KILL]["clauses"]]


def undecided(report: dict) -> list:
    return [k for k, d in sorted(report["conditions"].items())
            if d["relevant"][PASS]["count"] == 0]


# ---------------------------------------------------------- negative controls

def _rig(text: str, lo: int = None, hi: int = None, census=None, population=False,
         roles=(), ci: int = 0) -> dict:
    lo = 0 if lo is None else lo
    hi = len(text.rstrip(" .")) if hi is None else hi
    c = hr.clause_record("rig", 0, 0, ci, text, lo, hi, "rig")
    c.update(census_key=list(census) if census else None, population=population,
             fixture_roles=sorted(roles))
    return c


# A standalone `If ..., <operation>` with no trigger word: not an R1 shape.
STANDALONE = ("If you control an artifact, exile target creature, then return it to "
              "the battlefield.")


def negative_controls(rules: list) -> list:
    """Every applicable arm of every test, and every check, on rigged input."""
    names = ["Rig Card"]
    ev = lambda recs, rl=rules: evaluate(recs, rl, names)
    one = lambda c, k, rl=rules: ev([c], rl)["clauses"][0]["tests"][k]["outcome"]

    blink = "Exile target creature you control, then return that card to the battlefield."
    merged = _rig(blink, census=("exile", 0), population=True)
    merged["regions"] = [dict(merged["regions"][0], span=[0, 73])]
    two_same = _rig("Destroy target creature, then destroy target artifact.",
                    census=("destroy", 0), roles=[ROLE_TWO_OPS])
    two_same["regions"][1]["span"] = list(two_same["regions"][0]["span"])
    k5_dup = _rig("Destroy target creature, then destroy target artifact.",
                  census=("destroy", 0), population=True)
    k5_dup["regions"][1] = dict(k5_dup["regions"][0], ordinal=1)
    k5_dup["overlaps"] = [[0, 1]]
    k5_miss = _rig("Destroy target creature, then proliferate.", census=("destroy", 0),
                   population=True)
    k5_miss["detector_diff"]["only_corrected"] = [["counter", 3]]
    split = _rig("Return target creature to its owner's hand and target artifact to the "
                 "battlefield.", census=("bounce", 0), roles=[ROLE_SPLIT])
    put = _rig("Put target creature on top of its owner's library.")
    k7_bad = _rig("Destroy target creature, then proliferate.", census=("destroy", 0),
                  population=True)
    k7_bad["regions"][0]["span"][1] -= 3
    bad_rules = list(rules) + [{"id": "rig", "kind": "region", "cr": "CR 608.2c",
                                "pattern": "x", "oracle_id": "rig"}]
    r3_keyed = [dict(r, pattern=f"{r['pattern']} {names[0]}")
                if r["id"] == "group-back-reference" else r for r in rules]
    if r3_keyed == list(rules):
        fc.halt("the rule table carries no R3 group-back-reference entry")
    k3_of = lambda text: ev([_rig(text, census=("exile", 0), population=True)])[
        "clauses"][0]["tests"]["K3"]
    r3_hit = lambda t: [x for x in t.get("relations", []) if x.get("r3")]
    plural = k3_of("Exile target creature and target artifact, then return them to "
                   "the battlefield.")
    singular = k3_of("Exile target creature and target artifact, then return it to "
                     "the battlefield.")
    no_list = k3_of("Exile target creature or target artifact, then return them to "
                    "the battlefield.")
    ineligible = (
        ("duration", "Until end of turn, exile target creature, then return it to the "
                     "battlefield."),
        ("destination", "To the battlefield, exile target creature, then return it."),
        ("condition", STANDALONE),                  # standalone condition-marker
    )

    arms = [
        ("K1 KILL", lambda: one(merged, "K1") == KILL),
        ("K1 UNRESOLVED", lambda: one(_rig("Destroy target creature, then proliferate.",
                                           census=("destroy", 0), population=True),
                                      "K1") == UNRESOLVED),
        ("K2 KILL", lambda: one(two_same, "K2") == KILL),
        ("K2 UNRESOLVED", lambda: one(_rig("Destroy target creature, then destroy target "
                                           "artifact.", census=("destroy", 0),
                                           population=True), "K2") == UNRESOLVED),
        ("K3 KILL", lambda: one(_rig("Exile target creature and target artifact, then "
                                     "return that card to the battlefield.",
                                     census=("exile", 0), population=True), "K3") == KILL),
        ("K3 UNRESOLVED", lambda: one(_rig("Return it to its owner's hand.",
                                           census=("bounce", 0), population=True),
                                      "K3") == UNRESOLVED),
        ("K4 KILL", lambda: one(_rig(STANDALONE, census=("exile", 0), population=True),
                                "K4") == KILL),
        ("K4 UNRESOLVED", lambda: one(put, "K4") == UNRESOLVED),
        ("K5 KILL", lambda: one(k5_dup, "K5") == KILL),
        ("K5 UNRESOLVED", lambda: one(k5_miss, "K5") == UNRESOLVED),
        ("K6 KILL", lambda: one(split, "K6") == KILL),
        ("K6 UNRESOLVED", lambda: one(put, "K6") == UNRESOLVED),
        ("K7 KILL (card-keyed rule)", lambda: one(k7_bad, "K7", bad_rules) == KILL
         and one(_rig("Destroy target creature."), "K7", bad_rules) == KILL),
        ("K7 KILL (boundary not at a printed token)", lambda: one(k7_bad, "K7") == KILL),
        ("K7 KILL (a card-keyed R3 table entry)",
         lambda: one(_rig("Destroy target creature."), "K7", r3_keyed) == KILL),
        ("R3 never yields PASS: a plural reference to one coordinated list is "
         "UNRESOLVED",
         lambda: plural["outcome"] == UNRESOLVED and len(r3_hit(plural)) == 1
         and r3_hit(plural)[0]["outcome"] == UNRESOLVED
         and not any(x["outcome"] == PASS and x["kind"] == "back-reference"
                     for x in plural["relations"])),
        ("R3 does not apply to a singular reference ('it') to coordinated candidates, "
         "nor to a plural reference over candidates that fail the gap test: both keep "
         "KILL",
         lambda: singular["outcome"] == KILL and not r3_hit(singular)
         and no_list["outcome"] == KILL and not r3_hit(no_list)),
        ("a prefix span of an ineligible shape (duration, destination, standalone "
         "condition-marker) still KILLs K4",
         lambda: all(
             one(_rig(t, census=("exile", 0), population=True), "K4") == KILL
             and any(s["rule"] == "attach-ability-prefix" and s["role"] == role
                     and not s.get("r1_shape") for s in _rig(t)["role_spans"])
             for role, t in ineligible)),
        ("an R1 trigger prefix PASSES K4 (one attachment, to the ability)",
         lambda: one(_rig("When this creature enters, exile target creature, then "
                          "return it to the battlefield.", census=("exile", 0),
                          population=True), "K4") == PASS),
    ]
    # --check-not-killed: a real relevant kill fails; a control-only kill and a
    # kill on an irrelevant population clause do not.
    real = ev([_rig(STANDALONE, census=("exile", 0), population=True)])
    control_only = ev([_rig("Destroy target creature.", census=("destroy", 0),
                            population=True)])
    control_only["negative_controls"] = real["conditions"]
    irrelevant = ev([_rig("Destroy target creature, then proliferate.", population=True)])
    irrelevant["clauses"][0]["tests"]["K1"].update(outcome=KILL)
    irrelevant["conditions"] = summarize(irrelevant["clauses"])
    # --check-decided: an all-UNRESOLVED K1 (a fixture, so relevant) is
    # flagged; one relevant PASS clears it.
    put_fx = _rig("Put target creature on top of its owner's library.", roles=["rig-role"])
    unres = ev([put_fx])
    one_pass = ev([put_fx, _rig(blink, census=("exile", 0), population=True, ci=1)])
    # ATTACH-3-only clause: no census row, no C2 -- relevant to K4 by ATTACH-3 alone.
    a3 = _rig("If you control an artifact, destroy target creature, then proliferate.",
              population=True)
    a3_rep = ev([a3])
    # Mixed: one relevant K4 KILL, and K5 with zero PASS over its (zero)
    # relevant clauses.
    mixed = ev([_rig(STANDALONE, census=("exile", 0), population=True)])
    checks = [
        ("--check-not-killed fails on a rigged real kill",
         lambda: bool(not_killed_failures(real))),
        ("--check-not-killed passes on a rigged control-only kill",
         lambda: not not_killed_failures(control_only)),
        ("--check-not-killed passes on a KILL on an irrelevant population clause",
         lambda: not not_killed_failures(irrelevant)),
        ("--check-decided flags a rigged all-UNRESOLVED condition",
         lambda: "K1" in undecided(unres)),
        ("--check-decided clears that condition with one PASS",
         lambda: "K1" not in undecided(one_pass)),
        ("a rigged ATTACH-3-only clause with a K4 KILL is relevant and fails "
         "--check-not-killed",
         lambda: a3_rep["clauses"][0]["questions"] == ["ATTACH-3"]
         and a3_rep["clauses"][0]["tests"]["K4"]["outcome"] == KILL
         and a3_rep["clauses"][0]["tests"]["K4"]["relevant"]
         and ["K4", "rig:0:0:0"] in not_killed_failures(a3_rep)),
        ("a rigged mixed input yields 'killed' for the KILL's condition, fails "
         "--check-not-killed and is flagged by --check-decided",
         lambda: mixed["conditions"]["K4"]["result"] == RESULT_KILLED
         and ["K4", "rig:0:0:0"] in not_killed_failures(mixed)
         and "K5" in undecided(mixed)
         and mixed["conditions"]["K5"]["result"] == RESULT_NOT_KILLED),
    ]
    out = []
    for name, check in arms + checks:
        try:
            ok = check()
        except Exception as exc:                    # noqa: BLE001 -- reported, then halt
            fc.halt(f"negative control raised: {name}: {exc!r}")
        if not ok:
            fc.halt(f"negative control failed: {name}")
        out.append(name)
    return out


# --------------------------------------------------------------------- build

def ensure_regions() -> None:
    if not REGIONS.exists():
        p = subprocess.run([sys.executable, str(ROOT / hr.SCRIPT)], cwd=str(ROOT),
                           capture_output=True)
        if p.returncode != 0:
            sys.stderr.write(p.stderr.decode("utf-8", "replace"))
            fc.halt(f"h_region.py could not regenerate {REGIONS_REL}")
    with contextlib.redirect_stdout(io.StringIO()), \
            contextlib.redirect_stderr(io.StringIO()) as err:
        rc = hr.verify()
    if rc != 0:
        fc.halt(f"{REGIONS_REL} is stale (h_region.py --verify): "
                f"{err.getvalue().strip()}")


def build() -> dict:
    blob = hr.verify_interface()
    ensure_regions()
    doc = json.loads(REGIONS.read_text(encoding="utf-8"))
    if doc["interface"]["version"] != hr.INTERFACE_VERSION or doc["interface"]["blob"] != blob:
        fc.halt(f"{REGIONS_REL} was derived under {doc['interface']}, not "
                f"{hr.INTERFACE_VERSION} ({blob})")
    cards, _, _ = fc.load_corpus_gated()
    names = sorted({cards[c["address"]["oracle_id"]]["name"] for c in doc["clauses"]})
    report = evaluate(doc["clauses"], doc["rules"], names)
    changes = interface1_changes(doc["clauses"], doc["rules"], names, report)
    reach = rule_reach(doc["clauses"], report["clauses"])
    no_clause = [{"role": f["role"], "member_status": f["member_status"],
                  "member": m.get("name_as_recorded") or m["oracle_id"],
                  "reason": m.get("unresolved")}
                 for f in doc["fixtures"] for m in f["members"] if not m["clauses"]]
    no_clause += [{"role": f["role"], "member_status": f["member_status"],
                   "member": None, "reason": "no member (FIXTURES.json)"}
                  for f in doc["fixtures"] if not f["members"]]
    return {
        "schema": "oracle-compiler-c03-kill/0",
        "interface": {"version": hr.INTERFACE_VERSION, "blob": blob, "section": "I3 / I3a"},
        "rule_reach": reach,
        "changed_from_interface1": {
            "note": "[clause, census key, condition, interface/1 outcome, interface/2 "
                    "outcome, rule(s) whose effect alone changes it]; the full "
                    "per-clause record is under clauses[].interface1_changes",
            "rows": changes},
        "regions": {"path": REGIONS_REL, "sha256": _sha(REGIONS_REL)},
        "script": {"path": SCRIPT, "sha256": _sha(SCRIPT)},
        "questions_answered": ["ATTACH-1", "ATTACH-3", "C2"],
        "result_words": {"killed": RESULT_KILLED, "not_killed": RESULT_NOT_KILLED,
                         "never": "confirmed"},
        "fixtures_without_clauses": no_clause,
        "negative_controls": negative_controls(doc["rules"]),
        **report,
    }


def render(report: dict) -> bytes:
    return (json.dumps(report, indent=1, sort_keys=True, ensure_ascii=True)
            + "\n").encode("utf-8")


